# Store the marks of a student in a Python list[cite: 92]
marks = [85, 90, 78, 92, 88]

# Find the total number of subjects using the built-in len() function[cite: 92]
total_subjects = len(marks)

# Find the highest mark using the built-in max() function[cite: 92]
highest_mark = max(marks)

# Find the lowest mark using the built-in min() function[cite: 92]
lowest_mark = min(marks)

# Display the results
print(f"Marks List: {marks}")
print(f"Total Number of Subjects: {total_subjects}")
print(f"Highest Mark: {highest_mark}")
print(f"Lowest Mark: {lowest_mark}")