# Storing store variables and their data types
product_name = "Laptop"        # str
price = 5000.50                # float
quantity = 2                   # int
stock_availability = True      # bool

# Displaying the variables and their corresponding types
print("Product Name:", product_name, "| Type:", type(product_name))
print("Price:", price, "| Type:", type(price))
print("Quantity:", quantity, "| Type:", type(quantity))
print("Stock Availability:", stock_availability, "| Type:", type(stock_availability))