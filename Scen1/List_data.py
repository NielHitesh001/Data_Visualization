# Storing product details with appropriate data types
product_name = "Laptop"        # str
price = 5000.50                # float
quantity = 2                   # int
is_in_stock = True             # bool

# Displaying the variables and their data types
print("Product Name:", product_name, "| Type:", type(product_name))
print("Price:", price, "| Type:", type(price))
print("Quantity:", quantity, "| Type:", type(quantity))
print("In Stock:", is_in_stock, "| Type:", type(is_in_stock))